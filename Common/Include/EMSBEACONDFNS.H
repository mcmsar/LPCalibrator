    const ULONG LENGTH_BYTE_PREAMBLE = (LENGTH_BIT_PREAMBLE % 8) == 0 ? LENGTH_BIT_PREAMBLE / 8 : (LENGTH_BIT_PREAMBLE / 8) + 1;
