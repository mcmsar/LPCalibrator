    namespace User
    {
        const ULONG OFFSET_POSITION = 107;

        const ULONG LENGTH_BIT_POSITION = 25;

        const BYTE DEFAULT_POSITION_VALUE[] = { 0x7F, 0x07, 0xF8, 0x00 };
    };
