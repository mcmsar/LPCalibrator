    const ULONG LENGTH_BYTE_BEACONID = (LENGTH_BIT_BEACONID % 8) == 0 ? LENGTH_BIT_BEACONID / 8 : (LENGTH_BIT_BEACONID / 8) + 1;
    const ULONG LENGTH_BYTE_PDF1 = (LENGTH_BIT_PDF1 % 8) == 0 ? LENGTH_BIT_PDF1 / 8 : (LENGTH_BIT_PDF1 / 8) + 1;
    const ULONG LENGTH_BYTE_PDF2 = (LENGTH_BIT_PDF2 % 8) == 0 ? LENGTH_BIT_PDF2 / 8 : (LENGTH_BIT_PDF2 / 8) + 1;

    // generic beacon offsets
    const ULONG OFFSET_BITSYNC = 0;

    const ULONG OFFSET_FRAMESYNC_BIT = 15;
    const ULONG OFFSET_FRAMESYNC_BYTE = (OFFSET_FRAMESYNC_BIT % 8) == 0 ? OFFSET_FRAMESYNC_BIT / 8 : (OFFSET_FRAMESYNC_BIT / 8) + 1;

